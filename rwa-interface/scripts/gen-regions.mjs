import { writeFileSync } from 'node:fs';
import { format } from 'prettier';

const locales = ['en', 'zh-CN'];
const names = Object.fromEntries(locales.map((locale) => [locale, {}]));
for (let first = 65; first <= 90; first++) {
  for (let second = 65; second <= 90; second++) {
    const code = String.fromCharCode(first, second);
    if (code === 'ZZ') continue;
    const translated = locales.map((locale) =>
      new Intl.DisplayNames([locale], {
        type: 'region',
        fallback: 'none',
        style: code === 'HK' || code === 'MO' ? 'short' : 'long'
      }).of(code)
    );
    if (translated.every(Boolean))
      locales.forEach((locale, i) => {
        names[locale][code] = translated[i];
      });
  }
}
writeFileSync(
  new URL('../src/i18n/regions.ts', import.meta.url),
  await format(
    `// Generated by node scripts/gen-regions.mjs; do not edit by hand.\nexport const REGION_NAMES: Record<'en' | 'zh-CN', Record<string, string>> = ${JSON.stringify(names, null, 2)};\n`,
    { parser: 'typescript', singleQuote: true, trailingComma: 'none', printWidth: 140 }
  )
);
